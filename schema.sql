-- Tamilflix additive database setup.
-- IMPORTANT: This script does NOT delete or replace your existing movies table,
-- existing users, or existing Storage files.

create table if not exists public.tamilflix_admins (
  email text primary key
);

create table if not exists public.tamilflix_shows (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null check (category in ('marvel','anime','series','bigboss')),
  year integer,
  language text,
  poster_url text,
  backdrop_url text,
  description text,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.tamilflix_seasons (
  id bigint generated by default as identity primary key,
  show_id bigint not null references public.tamilflix_shows(id) on delete cascade,
  season_number integer not null,
  season_title text,
  created_at timestamptz not null default now(),
  unique(show_id, season_number)
);

create table if not exists public.tamilflix_episodes (
  id bigint generated by default as identity primary key,
  season_id bigint not null references public.tamilflix_seasons(id) on delete cascade,
  episode_number integer not null,
  episode_title text not null,
  thumbnail_url text,
  video_url text not null,
  created_at timestamptz not null default now(),
  unique(season_id, episode_number)
);

alter table public.tamilflix_admins enable row level security;
alter table public.tamilflix_shows enable row level security;
alter table public.tamilflix_seasons enable row level security;
alter table public.tamilflix_episodes enable row level security;

create or replace function public.is_tamilflix_admin()
returns boolean language sql stable security definer
set search_path = public
as $$
  select exists (
    select 1 from public.tamilflix_admins a
    where lower(a.email) = lower(coalesce(auth.jwt()->>'email',''))
  );
$$;

-- Public can read active catalogue. Admins can manage catalogue.
do $$ begin
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='tamilflix_shows' and policyname='Public read active shows') then
    create policy "Public read active shows" on public.tamilflix_shows for select using (is_active = true or public.is_tamilflix_admin());
  end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='tamilflix_shows' and policyname='Admins manage shows') then
    create policy "Admins manage shows" on public.tamilflix_shows for all using (public.is_tamilflix_admin()) with check (public.is_tamilflix_admin());
  end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='tamilflix_seasons' and policyname='Public read seasons') then
    create policy "Public read seasons" on public.tamilflix_seasons for select using (true);
  end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='tamilflix_seasons' and policyname='Admins manage seasons') then
    create policy "Admins manage seasons" on public.tamilflix_seasons for all using (public.is_tamilflix_admin()) with check (public.is_tamilflix_admin());
  end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='tamilflix_episodes' and policyname='Public read episodes') then
    create policy "Public read episodes" on public.tamilflix_episodes for select using (true);
  end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='tamilflix_episodes' and policyname='Admins manage episodes') then
    create policy "Admins manage episodes" on public.tamilflix_episodes for all using (public.is_tamilflix_admin()) with check (public.is_tamilflix_admin());
  end if;
end $$;

